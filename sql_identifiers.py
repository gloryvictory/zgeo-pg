"""Экранирование идентификаторов и подстановка в шаблоны SQL-запросов.

Модуль не зависит от QGIS и PyQt: именно поэтому подстановку имён объектов
можно покрыть обычными юнит-тестами. Это единственное место, где имя схемы,
таблицы или столбца попадает в текст запроса; значения пользователя и данные
из базы в текст запроса не подставляются вовсе — для них есть связанные
параметры ``QSqlQuery.addBindValue``.
"""

from __future__ import annotations

from .i18n import tr


def quote_ident(name) -> str:
    """Заключить идентификатор в кавычки, экранировав вложенные кавычки.

    Управляющие символы отбрасываются, кавычки удваиваются, поэтому
    подстановка не даёт выйти за пределы идентификатора. Пустое имя после
    очистки — ошибка: молча подставить ``""`` значит сломать запрос
    невнятным синтаксисом.
    """

    text = str(name)
    text = "".join(char for char in text if char.isprintable())
    if not text:
        raise ValueError(tr("Пустое имя объекта"))
    return '"' + text.replace('"', '""') + '"'


def render_sql(template: str, *args, **kwargs) -> str:
    """Подставить в шаблон запроса уже безопасные части.

    Шаблон — строковая константа модуля, а все подстановки прошли через
    :func:`quote_ident` (идентификаторы) либо являются числами.
    """

    return template.format(*args, **kwargs)
